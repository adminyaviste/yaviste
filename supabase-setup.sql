create table if not exists public.staff_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin', 'empleado'))
);

create table if not exists public.pedidos (
  id text primary key,
  folio bigint generated by default as identity unique not null,
  creado timestamptz not null default now(),
  estatus text not null default 'pendiente' check (estatus in ('pendiente', 'proceso', 'terminado')),
  estatus_pago text not null default 'pendiente' check (estatus_pago in ('pendiente', 'pagado')),
  datos jsonb not null,
  cliente_telefono text generated always as (
    case
      when length(regexp_replace(coalesce(datos #>> '{cliente,whatsapp}', ''), '[^0-9]', '', 'g')) = 10
        then '52' || regexp_replace(coalesce(datos #>> '{cliente,whatsapp}', ''), '[^0-9]', '', 'g')
      when length(regexp_replace(coalesce(datos #>> '{cliente,whatsapp}', ''), '[^0-9]', '', 'g')) = 13
        and left(regexp_replace(coalesce(datos #>> '{cliente,whatsapp}', ''), '[^0-9]', '', 'g'), 3) = '521'
        then '52' || substring(regexp_replace(coalesce(datos #>> '{cliente,whatsapp}', ''), '[^0-9]', '', 'g') from 4)
      else regexp_replace(coalesce(datos #>> '{cliente,whatsapp}', ''), '[^0-9]', '', 'g')
    end
  ) stored
);

alter table public.pedidos add column if not exists estatus_pago text not null default 'pendiente'
  check (estatus_pago in ('pendiente', 'pagado'));

