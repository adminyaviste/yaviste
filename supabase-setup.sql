create function public.datos_pedido_para_empleado(pedido_datos jsonb, pedido_estatus_pago text)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select jsonb_set(
    (
      jsonb_set(
        pedido_datos,
        '{productos}',
        coalesce((
          select jsonb_agg(producto.value - 'precio')
          from jsonb_array_elements(coalesce(pedido_datos -> 'productos', '[]'::jsonb)) as producto(value)
        ), '[]'::jsonb)
      )
      - 'cliente'
      - 'domicilioEntrega'
      - 'facturacion'
      - 'anticipo'
      - 'metodoPago'
      - 'ivaAplica'
      || jsonb_build_object('cliente', jsonb_build_object(
        'nombre', coalesce(pedido_datos #>> '{cliente,nombre}', ''),
        'whatsapp', coalesce(pedido_datos #>> '{cliente,whatsapp}', pedido_datos #>> '{cliente,telefono}', '')
      ))
    ),
    '{saldoPendiente}',
    case
      when pedido_estatus_pago <> 'pagado' then to_jsonb(greatest(
        0,
        round(
          coalesce((
            select sum(
              coalesce(nullif(producto.value ->> 'cantidad', '')::numeric, 0)
              * coalesce(nullif(producto.value ->> 'precio', '')::numeric, 0)
            )
            from jsonb_array_elements(coalesce(pedido_datos -> 'productos', '[]'::jsonb)) as producto(value)
          ), 0)
          * (1 + case when coalesce((pedido_datos ->> 'ivaAplica')::boolean, false) then 0.16 else 0 end)
          - coalesce(nullif(pedido_datos ->> 'anticipo', '')::numeric, 0),
          2
        )
      ))
      else 'null'::jsonb
    end,
    true
  )
$$;

