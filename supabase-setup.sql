create or replace function public.sincronizar_folio_pedidos()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  sequence_name text;
  max_folio bigint;
begin
  if coalesce(public.current_staff_role(), '') <> 'admin' then
    raise exception 'Solo un administrador puede sincronizar los folios.';
  end if;
  sequence_name := pg_get_serial_sequence('public.pedidos', 'folio');
  select coalesce(max(folio), 0) into max_folio from public.pedidos;
  if sequence_name is not null then
    if max_folio = 0 then
      perform setval(sequence_name, 1, false);
    else
      perform setval(sequence_name, max_folio, true);
    end if;
  end if;
end;
$$;

