drop function if exists public.actualizar_estatus_pedido(text, text);
create function public.actualizar_estatus_pedido(
  p_pedido_id text,
  p_nuevo_estatus text,
  p_nuevo_estatus_pago text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  pedido_actualizado public.pedidos%rowtype;
  pago_actual text;
begin
  if coalesce(public.current_staff_role(), '') <> 'empleado' then
    raise exception 'Solo un empleado puede usar esta funcion.';
  end if;
  if p_nuevo_estatus not in ('pendiente', 'proceso', 'terminado') then
    raise exception 'Estatus de pedido no valido.';
  end if;
  if p_nuevo_estatus_pago is null or p_nuevo_estatus_pago not in ('pendiente', 'pagado') then
    raise exception 'Estatus de pago no valido.';
  end if;

  select pedido.estatus_pago into pago_actual
  from public.pedidos as pedido
  where pedido.id = p_pedido_id
  for update;
  if not found then
    raise exception 'No se encontro el pedido solicitado.';
  end if;
  if pago_actual = 'pagado' and p_nuevo_estatus_pago <> pago_actual then
    raise exception 'Solo el administrador puede modificar un pago marcado como pagado.';
  end if;

  update public.pedidos as pedido
  set estatus = p_nuevo_estatus,
      estatus_pago = p_nuevo_estatus_pago
  where pedido.id = p_pedido_id
  returning pedido.* into pedido_actualizado;

  if not found then
    raise exception 'No se encontro el pedido solicitado.';
  end if;

  return jsonb_build_object(
    'id', pedido_actualizado.id,
    'folio', pedido_actualizado.folio,
    'creado', pedido_actualizado.creado,
    'estatus', pedido_actualizado.estatus,
    'estatus_pago', pedido_actualizado.estatus_pago,
    'datos', pedido_actualizado.datos
  );
end;
$$;

revoke all on function public.actualizar_estatus_pedido(text, text, text) from public, anon;
grant execute on function public.actualizar_estatus_pedido(text, text, text) to authenticated;

