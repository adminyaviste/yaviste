create or replace function public.sync_customer_order_summary()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  subtotal numeric;
begin
  select coalesce(sum(
    coalesce(nullif(item ->> 'cantidad', '')::numeric, 0)
    * coalesce(nullif(item ->> 'precio', '')::numeric, 0)
  ), 0)
  into subtotal
  from jsonb_array_elements(coalesce(new.datos -> 'productos', '[]'::jsonb)) as products(item);

  insert into public.pedidos_cliente (
    id, folio, cliente_telefono, fecha_entrega, total, anticipo, estatus, estatus_pago
  ) values (
    new.id,
    new.folio,
    new.cliente_telefono,
    new.datos ->> 'fechaEntrega',
    subtotal + case when coalesce((new.datos ->> 'ivaAplica')::boolean, false) then subtotal * 0.16 else 0 end,
    coalesce(nullif(new.datos ->> 'anticipo', '')::numeric, 0),
    new.estatus,
    new.estatus_pago
  )
  on conflict (id) do update set
    folio = excluded.folio,
    cliente_telefono = excluded.cliente_telefono,
    fecha_entrega = excluded.fecha_entrega,
    total = excluded.total,
    anticipo = excluded.anticipo,
    estatus = excluded.estatus,
    estatus_pago = excluded.estatus_pago;
  return new;
end;
$$;

drop trigger if exists sync_customer_order_summary on public.pedidos;
create trigger sync_customer_order_summary
after insert or update on public.pedidos
for each row execute function public.sync_customer_order_summary();
revoke all on function public.sync_customer_order_summary() from public, anon, authenticated;

create or replace function public.sincronizar_folio_pedidos()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  sequence_name text;
  max_folio bigint;
begin
  if coalesce(public.current_staff_role(), '') <> 'admin' then
    raise exception 'Solo un administrador puede sincronizar los folios.';
  end if;
  sequence_name := pg_get_serial_sequence('public.pedidos', 'folio');
  select coalesce(max(folio), 0) into max_folio from public.pedidos;
  if sequence_name is not null then
    if max_folio = 0 then
      perform setval(sequence_name, 1, false);
    else
      perform setval(sequence_name, max_folio, true);
    end if;
  end if;
end;
$$;

grant execute on function public.sincronizar_folio_pedidos() to authenticated;
revoke all on function public.sincronizar_folio_pedidos() from public, anon;
